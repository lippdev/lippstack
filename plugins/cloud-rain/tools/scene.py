"""Builds the Cloud Rain backdrop scenes (navy and black) from lipp-t3-theme assets.

    python3 tools/scene.py path/to/lipp-t3-theme hooks/scenes.ts
"""
import json
import random
import sys

from PIL import Image

SRC = sys.argv[1]   # lipp-t3-theme repo path
OUT = sys.argv[2]   # output .ts path

W, H = 240, 135
SCALE = 8           # one cloud pixel = 8 scene units -> 1920x1080
VW, VH = W * SCALE, H * SCALE

im = Image.open(f"{SRC}/assets/clouds.png").convert("RGB")
px = im.load()

def hexc(c): return "#%02x%02x%02x" % c

def gray(c):
    l = round(0.3 * c[0] + 0.59 * c[1] + 0.11 * c[2])
    l = round(l * 0.82)  # a touch darker so the black UI reads over it
    return (l, l, l)

def clouds(mapc):
    colors = {}
    for y in range(H):
        for x in range(W):
            colors.setdefault(px[x, y], 0)
            colors[px[x, y]] += 1
    order = sorted(colors, key=lambda c: -colors[c])
    base = order[0]
    paths = []
    for c in order[1:]:
        d = []
        cx, cy = 0, 0          # pen position after the last run
        for y in range(H):
            x = 0
            while x < W:
                if px[x, y] == c:
                    s = x
                    while x < W and px[x, y] == c:
                        x += 1
                    d.append(f"m{s - cx} {y - cy}h{x - s}" if d else f"M{s} {y}h{x - s}")
                    cx, cy = x, y
                else:
                    x += 1
        p = "".join(d).replace(" -", "-")
        paths.append(f'<path stroke="{hexc(mapc(c))}" d="{p}"/>')
    return hexc(mapc(base)), "".join(paths)

CELL_W, CELL_H = 8, 12
COLS, ROWS = 60, 80          # rain tile 480 x 960
DENSITY, TRAIL = 0.3, (6, 20)

def rain(fills, seed=11):
    rnd = random.Random(seed)
    layers = {k: [] for k in fills}
    for col in range(COLS):
        if rnd.random() > DENSITY:
            continue
        n = rnd.randint(*TRAIL)
        row0 = rnd.randint(0, ROWS - 1)
        digits = "".join(rnd.choice("0123456789") for _ in range(n))
        tail = max(1, int(n * 0.45))
        segs = [("tail", 0, digits[:tail]), ("body", tail, digits[tail:-1]), ("head", n - 1, digits[-1])]
        for off in (0, -ROWS):
            for layer, start, text in segs:
                ys = [(row0 + off + start + i + 1) * CELL_H - 2 for i in range(len(text))]
                keep = [(ch, y) for ch, y in zip(text, ys) if 0 < y < ROWS * CELL_H]
                if keep:
                    layers[layer].append(f'<text x="{" ".join([str(col * CELL_W + 4)] * len(keep))}" y="{" ".join(str(y) for _, y in keep)}">{"".join(ch for ch, _ in keep)}</text>')
    return "".join(f'<g {fills[k]}>' + "".join(layers[k]) + "</g>" for k in ("tail", "body", "head"))

TEXTURE_ROWS = ["789906764869458", "474844003902660", "560951367430817", "239109671305821", "572679496582423",
                "718489544999343", "338300044609013", "841128357753557", "211793764625295", "482659175181699"]

def texture():
    xs = " ".join(str(c * CELL_W + 4) for c in range(15))
    return "".join(f'<text x="{xs}" y="{(r + 1) * CELL_H - 2}">{row}</text>' for r, row in enumerate(TEXTURE_ROWS))

def scene(mapc, fills, tex_opacity, alt):
    base, paths = clouds(mapc)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VW} {VH}" preserveAspectRatio="xMidYMid slice">'
        '<style>'
        '.r{animation:fall 22s linear infinite}'
        '@keyframes fall{from{transform:translateY(0)}to{transform:translateY(960px)}}'
        '@media (prefers-reduced-motion:reduce){.r{animation:none}}'
        'text{font-family:ui-monospace,Consolas,monospace;font-weight:700;font-size:12px;text-anchor:middle}'
        '</style>'
        '<defs>'
        f'<pattern id="t" width="120" height="120" patternUnits="userSpaceOnUse"><g fill="#fff" fill-opacity="{tex_opacity}">{texture()}</g></pattern>'
        f'<pattern id="d" width="480" height="960" patternUnits="userSpaceOnUse">{rain(fills)}</pattern>'
        '</defs>'
        f'<rect width="{VW}" height="{VH}" fill="{base}"/>'
        f'<g transform="scale({SCALE}) translate(0 .5)" fill="none" stroke-width="1" shape-rendering="crispEdges">{paths}</g>'
        f'<rect width="{VW}" height="{VH}" fill="url(#t)"/>'
        f'<g class="r"><rect y="-960" width="{VW}" height="{VH + 960}" fill="url(#d)"/></g>'
        '</svg>'
    )

navy = scene(lambda c: c, {
    "tail": 'fill="#4d63d6" fill-opacity=".55"',
    "body": 'fill="#aebcff" fill-opacity=".8"',
    "head": 'fill="#fff"',
}, ".07", "")
preto = scene(gray, {
    "tail": 'fill="#6a6d73" fill-opacity=".55"',
    "body": 'fill="#c6c9cf" fill-opacity=".8"',
    "head": 'fill="#fff"',
}, ".06", "")

for name, s in (("navy", navy), ("black", preto)):
    print(name, len(s), file=sys.stderr)
    assert len(s) < 131072, name

with open(OUT, "w") as f:
    f.write("// Generated by scene.py from lipp-t3-theme's clouds and digit rain. Do not edit.\n")
    f.write(f"export const SCENE_NAVY = {json.dumps(navy)}\n")
    f.write(f"export const SCENE_BLACK = {json.dumps(preto)}\n")
